"""The eval contract shared by the eval runner and the ingest service: tool calls, the experiment
results the runner uploads to `/v1/experiments` (ADR-0023), and the replays `agenttrace replay`
uploads to `/v1/replays` (ADR-0029). Terms follow GLOSSARY.md."""

from datetime import datetime
from typing import Annotated, Any, Literal, Self
from uuid import UUID

from pydantic import (
    BaseModel,
    ConfigDict,
    Field,
    StringConstraints,
    model_serializer,
    model_validator,
)

from agenttrace.spans import SPAN_ID_PATTERN, TRACE_ID_PATTERN

ScorerName = Annotated[str, StringConstraints(pattern=r"^[a-z0-9][a-z0-9_-]{0,63}$")]
MAX_SAMPLES_PER_ITEM = 100
# The tag on every eval sample's root span; ingest leaves these out of production traffic.
EVAL_TAG = "agenttrace-eval"
MAX_SAMPLES_PER_REQUEST = 100


class Body(BaseModel):
    model_config = ConfigDict(extra="forbid")


class ToolCall(Body):
    """One tool call. In an expected trajectory `args` is a partial match: listed keys must be
    equal, others are ignored. In a recorded trajectory it's the call's full arguments."""

    tool: Annotated[str, StringConstraints(min_length=1)]
    args: dict[str, Any] | None = None

    @model_serializer(mode="wrap")
    def _omit_missing_args(self, handler) -> dict[str, Any]:
        data = handler(self)
        if data.get("args") is None:
            data.pop("args", None)
        return data


class ScorerSpec(Body):
    """One scorer as configured in `eval.yaml`. `name` is unique within an experiment."""

    name: ScorerName
    type: Annotated[str, StringConstraints(min_length=1, max_length=200)]
    threshold: Annotated[float, Field(ge=0, le=1)] = 1.0  # pass threshold (GLOSSARY.md)
    # The largest pass-rate drop versus the baseline the CI gate tolerates (ADR-0025).
    max_drop: Annotated[float, Field(ge=0, le=1)] = 0.05
    config: dict[str, Any] = Field(default_factory=dict)


class NewExperiment(Body):
    id: UUID  # generated by the runner, so a retried create is a no-op
    dataset_id: UUID
    dataset_version: Annotated[int, Field(ge=1)]
    name: Annotated[str, StringConstraints(max_length=200)] | None = None
    samples: Annotated[int, Field(ge=1, le=MAX_SAMPLES_PER_ITEM)] = 3
    scorers: Annotated[list[ScorerSpec], Field(min_length=1)]
    config: dict[str, Any]  # the parsed eval.yaml
    config_hash: Annotated[str, StringConstraints(pattern=r"^[0-9a-f]{64}$")]
    git_commit: Annotated[str, StringConstraints(max_length=200)] | None = None
    git_branch: Annotated[str, StringConstraints(max_length=500)] | None = None
    # On a pull request: where it branched from, and the branch it targets (ADR-0026).
    git_merge_base: Annotated[str, StringConstraints(max_length=200)] | None = None
    git_base_branch: Annotated[str, StringConstraints(max_length=500)] | None = None

    @model_validator(mode="after")
    def _unique_scorers(self) -> Self:
        names = [s.name for s in self.scorers]
        if len(names) != len(set(names)):
            raise ValueError("scorer names must be unique")
        return self


class ModelUsage(Body):
    """Token counts for one model across a sample. `input_tokens` excludes cached tokens."""

    model: Annotated[str, StringConstraints(min_length=1)]
    input_tokens: Annotated[int, Field(ge=0)] = 0
    output_tokens: Annotated[int, Field(ge=0)] = 0
    cache_read_tokens: Annotated[int, Field(ge=0)] = 0
    cache_write_5m_tokens: Annotated[int, Field(ge=0)] = 0
    cache_write_1h_tokens: Annotated[int, Field(ge=0)] = 0


class Score(Body):
    scorer: ScorerName
    score: Annotated[float, Field(ge=0, le=1)]
    reason: str | None = None


class AgentRun(Body):
    """One run of the agent and its scores: an experiment's sample or a replay run. A scorer
    skipped for the run (it lacks that expectation) has no score; an errored run (`error` set)
    scores 0 on every scorer."""

    trace_id: Annotated[str, StringConstraints(pattern=TRACE_ID_PATTERN)] | None = None
    started_at: datetime
    latency_ms: Annotated[float, Field(ge=0)]
    output: Any = None
    output_truncated: bool = False
    trajectory: list[ToolCall] = Field(default_factory=list)
    error: str | None = None
    usage: list[ModelUsage] = Field(default_factory=list)
    judge_usage: list[ModelUsage] = Field(default_factory=list)  # LLM judge calls (ADR-0027)
    scores: list[Score] = Field(default_factory=list)

    @model_validator(mode="after")
    def _one_score_per_scorer(self) -> Self:
        names = [s.scorer for s in self.scores]
        if len(names) != len(set(names)):
            raise ValueError("one score per scorer")
        return self


class SampleResult(AgentRun):
    """One sample of an experiment."""

    item_id: UUID
    sample_index: Annotated[int, Field(ge=0)]


class SampleBatch(Body):
    samples: Annotated[list[SampleResult], Field(min_length=1, max_length=MAX_SAMPLES_PER_REQUEST)]


class Finish(Body):
    status: Literal["completed", "failed"]
    error: str | None = None  # why the runner failed


class SpanRef(Body):
    trace_id: Annotated[str, StringConstraints(pattern=TRACE_ID_PATTERN)]
    span_id: Annotated[str, StringConstraints(pattern=SPAN_ID_PATTERN)]


ToolMode = Literal["live", "recorded"]
MAX_WARNINGS = 1000


class StepWarning(Body):
    """A fork's prefix LLM call whose request differed from its recording; the stub was still
    returned (ADR-0040). `step` counts LLM and tool spans from 0."""

    step: Annotated[int, Field(ge=0)]
    fields: Annotated[
        list[Annotated[str, StringConstraints(min_length=1, max_length=100)]],
        Field(min_length=1, max_length=100),
    ]


class NewReplay(Body):
    """A replay (ADR-0029). It's scored when it names the draft item it's scored against, with
    that item's revision and `eval.yaml`'s scorers (ADR-0030); otherwise it has neither."""

    id: UUID  # generated by the CLI, so a retried create is a no-op
    replay_of: SpanRef  # the original trace's root span, never another replay's (ADR-0028)
    # A fork's fork point: the step it goes live at, in the trace it forked, which may be a
    # replay run (ADR-0040). None for a whole-trace replay.
    fork_of: SpanRef | None = None
    tool_mode: ToolMode = "live"  # `recorded` answers every tool call from the recording
    runs: Annotated[int, Field(ge=1, le=MAX_SAMPLES_PER_ITEM)] = 3
    item_id: UUID | None = None
    item_rev: Annotated[int, Field(ge=1)] | None = None
    scorers: list[ScorerSpec] = Field(default_factory=list)
    config: dict[str, Any] | None = None  # the parsed eval.yaml, when there is one
    config_hash: Annotated[str, StringConstraints(pattern=r"^[0-9a-f]{64}$")] | None = None
    git_commit: Annotated[str, StringConstraints(max_length=200)] | None = None
    git_branch: Annotated[str, StringConstraints(max_length=500)] | None = None
    git_dirty: bool | None = None  # uncommitted changes in the working tree

    @model_validator(mode="after")
    def _scored_or_not(self) -> Self:
        if (self.item_id is None) != (self.item_rev is None):
            raise ValueError("item_id and item_rev go together")
        if (self.item_id is None) != (not self.scorers):
            raise ValueError("a scored replay names its item and scorers; an unscored one neither")
        names = [s.name for s in self.scorers]
        if len(names) != len(set(names)):
            raise ValueError("scorer names must be unique")
        return self

    @property
    def scored(self) -> bool:
        return self.item_id is not None


class ReplayRunResult(AgentRun):
    """One replay run. A fork run whose prefix left the recording (a tool call with no match)
    names the step it went live at as `diverged_at` (ADR-0040)."""

    run_index: Annotated[int, Field(ge=0)]
    diverged_at: Annotated[int, Field(ge=0)] | None = None
    warnings: Annotated[list[StepWarning], Field(max_length=MAX_WARNINGS)] = Field(
        default_factory=list
    )


class ReplayRunBatch(Body):
    runs: Annotated[list[ReplayRunResult], Field(min_length=1, max_length=MAX_SAMPLES_PER_REQUEST)]
